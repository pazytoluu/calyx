-- 1. USERS — Table centrale
CREATE TABLE users (
                       id                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email              VARCHAR2(255) NOT NULL,
                       password_hash      VARCHAR2(255) NOT NULL,
                       first_name         VARCHAR2(100) NOT NULL,
                       last_name          VARCHAR2(100) NOT NULL,
                       role               VARCHAR2(20) NOT NULL,
                       is_active_account  NUMBER(1) DEFAULT 1 NOT NULL,
                       created_at         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                       updated_at         TIMESTAMP,
                       CONSTRAINT uq_users_email UNIQUE (email),
                       CONSTRAINT ck_users_role CHECK (role IN ('admin', 'courtier', 'client')),
                       CONSTRAINT ck_users_active CHECK (is_active_account IN (0, 1))
);

CREATE INDEX idx_users_email ON users(email);


-- 2. BROKER_PROFILES — Profil courtier
CREATE TABLE broker_profiles (
                                 id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 user_id        NUMBER NOT NULL,
                                 company_name   VARCHAR2(255) NOT NULL,
                                 orias_number   VARCHAR2(50) NOT NULL,
                                 siret          VARCHAR2(20),
                                 phone          VARCHAR2(30) NOT NULL,
                                 address        VARCHAR2(255) NOT NULL,
                                 postal_code    VARCHAR2(20) NOT NULL,
                                 city           VARCHAR2(100) NOT NULL,
                                 created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                                 CONSTRAINT uq_broker_user_id UNIQUE (user_id),
                                 CONSTRAINT uq_broker_orias UNIQUE (orias_number),
                                 CONSTRAINT fk_broker_user FOREIGN KEY (user_id)
                                     REFERENCES users(id) ON DELETE CASCADE
);


-- 3. CLIENT_PROFILES — Profil client
CREATE TABLE client_profiles (
                                 id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 user_id         NUMBER NOT NULL,
                                 broker_id       NUMBER,
                                 phone           VARCHAR2(30) NOT NULL,
                                 address         VARCHAR2(255) NOT NULL,
                                 postal_code     VARCHAR2(20) NOT NULL,
                                 city            VARCHAR2(100) NOT NULL,
                                 insurance_type  VARCHAR2(100),
                                 created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                                 CONSTRAINT uq_client_user_id UNIQUE (user_id),
                                 CONSTRAINT fk_client_user FOREIGN KEY (user_id)
                                     REFERENCES users(id) ON DELETE CASCADE,
                                 CONSTRAINT fk_client_broker FOREIGN KEY (broker_id)
                                     REFERENCES broker_profiles(id) ON DELETE SET NULL
);

CREATE INDEX idx_client_broker_id ON client_profiles(broker_id);


-- 4. OFFERS — Catalogue des produits
CREATE TABLE offers (
                        id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        slug         VARCHAR2(100) NOT NULL,
                        title        VARCHAR2(255) NOT NULL,
                        description  CLOB,
                        price        NUMBER(10,2) NOT NULL,
                        is_active    NUMBER(1) DEFAULT 1 NOT NULL,
                        created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                        CONSTRAINT uq_offers_slug UNIQUE (slug),
                        CONSTRAINT ck_offers_active CHECK (is_active IN (0, 1)),
                        CONSTRAINT ck_offers_price CHECK (price >= 0)
);


-- 5. ORDERS — Commandes / souscriptions
CREATE TABLE orders (
                        id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id      NUMBER NOT NULL,
                        offer_id     NUMBER NOT NULL,
                        status       VARCHAR2(30) DEFAULT 'pending' NOT NULL,
                        amount_paid  NUMBER(10,2),
                        created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                        paid_at      TIMESTAMP,
                        CONSTRAINT fk_orders_user FOREIGN KEY (user_id)
                            REFERENCES users(id) ON DELETE CASCADE,
                        CONSTRAINT fk_orders_offer FOREIGN KEY (offer_id)
                            REFERENCES offers(id),
                        CONSTRAINT ck_orders_status CHECK (status IN ('pending', 'paid', 'cancelled', 'refunded'))
);

CREATE INDEX idx_orders_user_id ON orders(user_id);
CREATE INDEX idx_orders_offer_id ON orders(offer_id);


-- 6. DISPUTES — Litiges / dossiers d'audit
CREATE TABLE disputes (
                          id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          client_id     NUMBER NOT NULL,
                          broker_id     NUMBER NOT NULL,
                          title         VARCHAR2(255) NOT NULL,
                          description   CLOB,
                          status        VARCHAR2(30) DEFAULT 'open' NOT NULL,
                          priority      VARCHAR2(20) DEFAULT 'medium' NOT NULL,
                          created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                          resolved_at   TIMESTAMP,
                          CONSTRAINT fk_disputes_client FOREIGN KEY (client_id)
                              REFERENCES client_profiles(id) ON DELETE CASCADE,
                          CONSTRAINT fk_disputes_broker FOREIGN KEY (broker_id)
                              REFERENCES broker_profiles(id) ON DELETE CASCADE,
                          CONSTRAINT ck_disputes_status CHECK (status IN ('open', 'in_progress', 'resolved', 'escalated')),
                          CONSTRAINT ck_disputes_priority CHECK (priority IN ('low', 'medium', 'high'))
);

CREATE INDEX idx_disputes_client_id ON disputes(client_id);
CREATE INDEX idx_disputes_broker_id ON disputes(broker_id);


