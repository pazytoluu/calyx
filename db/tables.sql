-- 2. AUDITS — Dossiers d'audit soumis par les clients
CREATE TABLE audits (
                        id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        client_id    NUMBER NOT NULL,
                        order_id     NUMBER NOT NULL,
                        broker_id    NUMBER,                          -- assigné par l'admin
                        title        VARCHAR2(255) NOT NULL,
                        description  CLOB,
                        priority     VARCHAR2(20) DEFAULT 'medium' NOT NULL,
                        status       VARCHAR2(30) DEFAULT 'pending' NOT NULL,
                        created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                        assigned_at  TIMESTAMP,
                        resolved_at  TIMESTAMP,
                        CONSTRAINT fk_audits_client FOREIGN KEY (client_id)
                            REFERENCES client_profiles(id) ON DELETE CASCADE,
                        CONSTRAINT fk_audits_order FOREIGN KEY (order_id)
                            REFERENCES orders(id) ON DELETE CASCADE,
                        CONSTRAINT fk_audits_broker FOREIGN KEY (broker_id)
                            REFERENCES broker_profiles(id) ON DELETE SET NULL,
                        CONSTRAINT ck_audits_priority CHECK (priority IN ('low', 'medium', 'high')),
                        CONSTRAINT ck_audits_status   CHECK (status IN ('pending', 'assigned', 'in_progress', 'resolved'))
);

CREATE INDEX idx_audits_client_id ON audits(client_id);
CREATE INDEX idx_audits_broker_id ON audits(broker_id);
CREATE INDEX idx_audits_order_id  ON audits(order_id);


-- 3. AUDIT_FILES — Fichiers joints à un audit
CREATE TABLE audit_files (
                             id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             audit_id    NUMBER NOT NULL,
                             filename    VARCHAR2(255) NOT NULL,   -- nom original du fichier
                             stored_name VARCHAR2(255) NOT NULL,   -- nom UUID sur le disque
                             mime_type   VARCHAR2(100) NOT NULL,
                             file_size   NUMBER NOT NULL,          -- taille en octets
                             uploaded_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                             CONSTRAINT fk_audit_files_audit FOREIGN KEY (audit_id)
                                 REFERENCES audits(id) ON DELETE CASCADE
);

CREATE INDEX idx_audit_files_audit_id ON audit_files(audit_id);

